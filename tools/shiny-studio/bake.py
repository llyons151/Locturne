"""Bakes every shiny into the app: recoloured sky and moon pictures in assets/moons/shiny/, and their colours in
src/features/moons/shiny-colors.ts (read by shiny-look.ts). Run by the studio's Bake button or `python3 bake.py`.
Only moons whose settings changed since the last bake are re-rendered (stamp in bake-stamp.json)."""
import json, pathlib, sys
import numpy as np
from PIL import Image
from shinylib import ROOT, moons, shift_hex

HERE = pathlib.Path(__file__).parent
OUT = ROOT / 'assets' / 'moons' / 'shiny'
TS = ROOT / 'src' / 'features' / 'moons' / 'shiny-colors.ts'
STAMP = HERE / 'bake-stamp.json'


def rgb_to_hsv(a):
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    mx = a.max(-1); mn = a.min(-1); d = mx - mn
    h = np.zeros_like(mx)
    m = d > 1e-6
    rc = np.where(m, (mx - r) / np.where(m, d, 1), 0); gc = np.where(m, (mx - g) / np.where(m, d, 1), 0); bc = np.where(m, (mx - b) / np.where(m, d, 1), 0)
    h = np.where(r == mx, bc - gc, np.where(g == mx, 2 + rc - bc, 4 + gc - rc))
    h = np.where(m, (h / 6) % 1, 0)
    s = np.where(mx > 1e-6, d / np.where(mx > 1e-6, mx, 1), 0)
    return h, s, mx


def hsv_to_rgb(h, s, v):
    i = np.floor(h * 6).astype(int) % 6
    f = h * 6 - np.floor(h * 6)
    p = v * (1 - s); q = v * (1 - s * f); t = v * (1 - s * (1 - f))
    r = np.choose(i, [v, q, p, p, t, v]); g = np.choose(i, [t, v, v, q, p, p]); b = np.choose(i, [p, p, t, v, v, q])
    return np.stack([r, g, b], -1)


def shift_image(src, dst, p):
    im = Image.open(src)
    alpha = im.getchannel('A') if im.mode in ('RGBA', 'LA') else None
    a = np.asarray(im.convert('RGB')).astype(np.float32) / 255
    h, s, v = rgb_to_hsv(a)
    hh, ww = v.shape
    pos = (np.arange(ww)[None, :] / max(1, ww - 1) + np.arange(hh)[:, None] / max(1, hh - 1)) / 2
    h = ((p['a'] + (p['b'] - p['a']) * v + p['sweep'] * (pos - 0.5)) / 360) % 1
    s = np.clip(np.maximum(s, p['min']) * p['sat'], 0, 1)
    out = Image.fromarray((np.clip(hsv_to_rgb(h, s, v), 0, 1) * 255 + 0.5).astype(np.uint8))
    if alpha is not None:
        out.putalpha(alpha)
    out.save(dst, 'WEBP', quality=86, method=4)


def main():
    params = json.loads((HERE / 'shiny.json').read_text())
    stamp = json.loads(STAMP.read_text()) if STAMP.exists() else {}
    OUT.mkdir(parents=True, exist_ok=True)
    only = set(sys.argv[1:])
    lines = ['// Generated by tools/shiny-studio/bake.py from tools/shiny-studio/shiny.json (`npm run shiny-studio`). Do not edit by hand.',
             "import type { ImageSourcePropType } from 'react-native';", '',
             '/** Each moon\'s shiny: its colours and recoloured pictures (shiny-look.ts). */',
             'export const SHINY_COLORS: Record<string, { glow: string; orb: [string, string, string, string]; skyColors: [string, string, string, string]; sky: ImageSourcePropType; moon: ImageSourcePropType }> = {']
    done = 0
    for m in moons():
        p = params[m['id']]
        key = json.dumps(p, sort_keys=True)
        sky, moon = OUT / f"{m['id']}-sky.webp", OUT / f"{m['id']}-moon.webp"
        if (not only or m['id'] in only) and (stamp.get(m['id']) != key or not sky.exists() or not moon.exists()):
            shift_image(ROOT / 'assets' / m['skyImg'], sky, p)
            shift_image(ROOT / 'assets' / m['moonImg'], moon, p)
            stamp[m['id']] = key
            done += 1
        c = {'glow': shift_hex(m['glow'], p), 'orb': [shift_hex(x, p) for x in m['orb']], 'skyColors': [shift_hex(x, p) for x in m['skyColors']]}
        lines.append(f"  {json.dumps(m['id'])}: {{ glow: {json.dumps(c['glow'])}, orb: {json.dumps(c['orb'])}, skyColors: {json.dumps(c['skyColors'])}, "
                     f"sky: require('@/assets/moons/shiny/{m['id']}-sky.webp'), moon: require('@/assets/moons/shiny/{m['id']}-moon.webp') }},")
    lines.append('};')
    TS.write_text('\n'.join(lines) + '\n')
    STAMP.write_text(json.dumps(stamp, indent=1))
    print(f'baked {done} moons; {TS.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
