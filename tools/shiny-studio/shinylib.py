"""The shiny transform, shared by bake.py and (mirrored exactly in index.html) the studio's preview.
A two-tone holographic finish (user, 2026-11-23: "weirder, you should just be able to tell it's a shiny"):
per pixel in HSV, the hue runs from `a` in the shadows to `b` in the highlights (by brightness), plus a sweep of
`sweep` degrees across the picture's diagonal like a holo card; saturation is at least `min`, times `sat`; the
brightness is kept, so the moon's craters and the sky's light stay where they were. Colours (no position) sit
mid-sweep."""
import colorsys, json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
DATA = ROOT / 'src' / 'features' / 'moons' / 'moon-data.ts'


def moons():
    """Every moon from moon-data.ts (generated by the moon lab): id, name, glow, orb, skyColors, sky/moon image paths."""
    out = []
    for line in DATA.read_text().splitlines():
        m = re.match(r'\s*(\{ "id".*\}),?\s*$', line)
        if not m:
            continue
        body = m.group(1)
        imgs = dict(re.findall(r"(\w+): require\('@/assets/moons/([\w-]+\.webp)'\)", body))
        js = re.sub(r",\s*\w+: require\([^)]*\)", '', body)
        d = json.loads(js)
        d['skyImg'] = 'moons/' + imgs['sky'] if 'sky' in imgs else 'onboarding/night-sky-moonless.png'
        d['moonImg'] = 'moons/' + imgs['moon'] if 'moon' in imgs else 'onboarding/moon-frosted.png'
        out.append(d)
    return out


def hexrgb(h):
    n = int(h.lstrip('#'), 16)
    return ((n >> 16) & 255) / 255, ((n >> 8) & 255) / 255, (n & 255) / 255


def rgbhex(r, g, b):
    return '#%02X%02X%02X' % tuple(max(0, min(255, round(x * 255))) for x in (r, g, b))


def shift(h, s, v, p, pos=0.5):
    """One colour in HSV (each 0..1); `pos` is its place along the picture's diagonal (0..1)."""
    hue = (p['a'] + (p['b'] - p['a']) * v + p['sweep'] * (pos - 0.5)) / 360 % 1
    sat = max(0.0, min(1.0, max(s, p['min']) * p['sat']))
    return hue, sat, v


def shift_hex(c, p):
    h, s, v = colorsys.rgb_to_hsv(*hexrgb(c))
    return rgbhex(*colorsys.hsv_to_rgb(*shift(h, s, v, p)))


# Clashing two-tone pairs (shadows, highlights), none of them a regular moon's look.
PAIRS = [(300, 185), (275, 95), (330, 200), (25, 265), (160, 320), (45, 300), (195, 345), (120, 285), (350, 60), (230, 140)]


def default_params(glow, i=0):
    """A starting shiny: walks the clashing pairs by the moon's place (so neighbours differ), skipping any pair
    with a colour too close to the moon's own."""
    h, s, v = colorsys.rgb_to_hsv(*hexrgb(glow))
    hue = h * 360
    d = lambda x: min(abs(x % 360 - hue), 360 - abs(x % 360 - hue))
    for k in range(len(PAIRS)):
        a, b = PAIRS[(i * 3 + k) % len(PAIRS)]
        if s < 0.18 or min(d(a), d(b)) > 45:
            break
    return {'a': a, 'b': b if b > a else b + 360, 'sweep': 70, 'sat': 1.1, 'min': 0.45}
